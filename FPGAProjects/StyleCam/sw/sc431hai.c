int sc431hai_init(void)
{
    uint8_t hi, lo;
    if (hal_i2c_read16(SC_ADDR, 0x3107, &hi) || hal_i2c_read16(SC_ADDR, 0x3108, &lo)) return -1;
    if (hi != 0xCD || lo != 0x6B) return -2;          // SENSOR ID = 0xCD6B
    if (init_tab[0].reg != 0xFFFF) {
        hal_i2c_write16(SC_ADDR, 0x0103, 0x01);        // 软复位
        hal_delay_ms(10);
        for (const sc_reg_t *p = init_tab; p->reg != 0xFFFF; p++)
            if (hal_i2c_write16(SC_ADDR, p->reg, p->val)) return -3;
        hal_i2c_write16(SC_ADDR, 0x0100, 0x01);        // 开流
    }
    return 0;
}

void sc431hai_stream(int on)
{
    // 低功耗软睡眠进出顺序（手册表 1-1）：关流 0x302c=0x0f、0x0100=0；开流 0x302c=0x00、0x0100=1
    hal_i2c_write16(SC_ADDR, 0x302C, on ? 0x00 : 0x0F);
    hal_i2c_write16(SC_ADDR, 0x0100, on ? 0x01 : 0x00);
}

// 曝光：单位半行，范围 4 .. 2*VTS-11（线性模式）；第 N 帧写入、第 N+2 帧生效
void sc431hai_set_exposure(uint32_t half_rows)
{
    if (half_rows < 4) half_rows = 4;
    hal_i2c_write16(SC_ADDR, 0x3E00, (uint8_t)((half_rows >> 12) & 0x0F));
    hal_i2c_write16(SC_ADDR, 0x3E01, (uint8_t)(half_rows >> 4));
    hal_i2c_write16(SC_ADDR, 0x3E02, (uint8_t)((half_rows & 0x0F) << 4));
}

// 模拟增益：粗档 0x00/0x80/0x81/0x83/0x87/0x8F 与细档 0x20..0x3F（手册表 2-7）
void sc431hai_set_again(uint8_t coarse, uint8_t fine)
{
    hal_i2c_write16(SC_ADDR, 0x3E08, coarse);
    hal_i2c_write16(SC_ADDR, 0x3E09, fine);
}
