"""Replay saved independent golden vectors with the current IN and real CNN RTL.

The golden assets were generated by the existing official-reference scripts.
Their model files must match this workspace before any asset is accepted.
"""
from pathlib import Path
import hashlib,json,os,re,shutil,subprocess,sys,time
from compact_in_constants import compact

ROOT=Path(__file__).resolve().parent
REFERENCE=Path(os.environ.get('STYLECAM_REFERENCE_PROJECT',str(ROOT))).resolve()
OUT=ROOT/Path(os.environ.get('STYLECAM_IN_SIM_SUBDIR','validation/in_resource_20261017/integrated'))
OUT=OUT.resolve();OUT.relative_to(ROOT);OUT.mkdir(parents=True,exist_ok=True)
BIN=Path(os.environ.get('ICARUS_BIN',ROOT.parent/'tools/iverilog/mingw64/bin'))
sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
for name in ['net_blob.bin','qparams.json','qparams.npz','in_constants.mem']:
 assert sha(ROOT/'model'/name)==sha(REFERENCE/'model'/name),f'Different golden model: {name}'
cases=sys.argv[1:] or ['math','engine','vga'];assert set(cases)<=set(['math','engine','vga'])
for name in cases:
 folder=OUT/name;folder.mkdir(exist_ok=True)
 hashes={}
 def asset(source,destination):
  shutil.copy2(source,destination);hashes[destination.relative_to(ROOT).as_posix()]=sha(destination)
 if name=='math':
  source=REFERENCE/'validation/in_math'
  asset(source/'vectors.hex',folder/'vectors.hex')
  tb=(source/'tb.v').read_text().replace('validation/in_math/',folder.relative_to(ROOT).as_posix()+'/')
  files=['sc_in_math','sc_in_alu'];extra=[]
 elif name=='engine':
  source=REFERENCE/'validation/video_engine'
  for f in [*source.glob('*.hex'),*source.glob('constants.mem*')]:asset(f,folder/f.name)
  compact(folder/'constants.mem')
  expected_net=re.sub(r'\.(W|H|WL|HL)\((\d+)\)',lambda m:f'.{m[1]}({int(m[2])//20})',(ROOT/'rtl/stylenet_top.v').read_text(encoding='utf-8'))
  golden_net=(source/'net.v').read_text(encoding='utf-8')
  # Golden pixels predate the PE12 throughput change and removal of the unused
  # last-layer IN statistics tap. Permit exactly those implementation changes.
  golden_net=golden_net.replace('.PE(6), .CFG_PE(6)','.PE(12), .CFG_PE(6)')
  golden_net=re.sub(r"\s*5'd12: begin tv = sv12; ta = sa12; tc = sc12; end",'',golden_net)
  clean=lambda s:re.sub(r'\s+','',re.sub(r'//[^\n]*','',s))
  assert clean(golden_net)==clean(expected_net),'Golden network geometry differs'
  (folder/'net.v').write_text(expected_net,encoding='utf-8')
  tb=(source/'tb.v').read_text().replace('validation/video_engine/',folder.relative_to(ROOT).as_posix()+'/')
  files=['sc_engine','sc_in_refresh','sc_in_math','sc_in_alu','common','conv_layer','mac','requant','swg3','swg3b']
  extra=['-DCPU_BLOB']
 else:
  source=REFERENCE/'validation/vga_performance/optimized'
  for f in ['input.hex','expected.hex','records.hex']:asset(source/f,folder/f)
  tb=(REFERENCE/'validation/latency_vga/tb.v').read_text().replace('validation/vga_performance/optimized/',folder.relative_to(ROOT).as_posix()+'/')
  files=['sc_engine_cdc','sc_engine','sc_in_refresh','sc_in_math','sc_in_alu','common','conv_layer','mac','requant','swg3','swg3b','stylenet_top']
  extra=[]
 tbfile=folder/'tb.v';tbfile.write_text(tb)
 sources=[ROOT/f'rtl/{s}.v' for s in files]+[tbfile]
 if name=='engine':sources+=[folder/'net.v']
 exe=folder/'test.vvp'
 subprocess.run([str(BIN/'iverilog.exe'),'-g2012',*extra,'-s','tb','-o',str(exe),*[str(f) for f in sources]],cwd=ROOT,check=True)
 stamp=time.monotonic();print('Running',name,flush=True)
 with (folder/'simulation.log').open('w') as log:
  proc=subprocess.run([str(BIN/'vvp.exe'),'-i',str(exe)],cwd=ROOT,stdout=log,stderr=subprocess.STDOUT)
 log=(folder/'simulation.log').read_text();print(log,flush=True)
 assert proc.returncode==0 and 'PASS' in log,name
 result=dict(passed=True,seconds=round(time.monotonic()-stamp,2),golden_model_unchanged=True,
  source_sha256={f.relative_to(ROOT).as_posix():sha(f) for f in sources},vector_sha256=hashes)
 if name=='engine':
  result.update(styles=[0,1,2],pixels_exact=6912,coefficients_exact=936,frames=9)
  result['source_sha256'].update({f.relative_to(ROOT).as_posix():sha(f) for f in folder.glob('constants.mem*')})
 if name=='math':result.update(vectors=3273,official_statistics=True,VGA_statistics=True)
 if name=='vga':
  m=re.search(r'PASS VGA CDC pixels=(\d+) job_cycles=(\d+) pass_cycles=(\d+) input_stalls=(\d+) output_stalls=(\d+) elapsed_ns=([\d.]+)',log);assert m
  result['measurements']={k:int(v) for k,v in zip(['pixels','job_cycles','pass_cycles','input_stalls','output_stalls'],m.groups()[:5])}
  result.update(pixels_exact=307200,simulated_job_ms=float(m[6])/1e6,includes_dynamic_IN=True)
  assert result['simulated_job_ms']<1000/30,'VGA engine misses the 30 fps computation budget'
 (folder/'result.json').write_text(json.dumps(result,indent=2)+'\n')
