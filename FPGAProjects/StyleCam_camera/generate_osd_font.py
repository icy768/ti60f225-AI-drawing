"""Pack the native OSD font and its glyph offsets into one 1024x10 DPRAM.

Only empty leading/trailing rows are removed. Regenerate after changing the
font; --check verifies the checked-in header without modifying it.
"""
from pathlib import Path
import hashlib, sys

ROOT=Path(__file__).resolve().parent
source=ROOT/'model/font8x16.mem'
target=ROOT/'rtl/sc_osd_font.vh'
values=[int(x,16) for x in source.read_text().split()]
assert len(values)==1536 and all(0<=x<256 for x in values)
packed=[0]*1024;pointer=96;bounds=[]
for glyph in range(96):
    rows=[r for r in range(16) if values[glyph*16+r]]
    lo,hi=(min(rows),max(rows)+1) if rows else (0,0)
    bounds.append((lo,hi));packed[glyph]=(pointer-lo)&1023
    for row in range(lo,hi):
        assert pointer<1024,'Font no longer fits; use the generic FONT implementation'
        packed[pointer]=values[glyph*16+row];pointer+=1
number=sum(word<<(10*i) for i,word in enumerate(packed))
text=f'''// Generated by generate_osd_font.py; do not edit the packed constants.
// font8x16.mem SHA256: {hashlib.sha256(source.read_bytes()).hexdigest()}
// 96 offsets + {pointer-96} retained rows = {pointer}/1024 ten-bit words.
// Port A reads the current glyph offset; port B reads the preceding row.
// These replace the font-address register and original synchronous ROM, so
// text-to-video latency stays unchanged. Both ports are permanently read-only.
module sc_osd_font(input clk,input [6:0] glyph,input [3:0] row,output [7:0] data);
 wire [9:0] offset,word;reg [3:0] row_d;reg valid_d,valid_q;
 reg [3:0] lo,hi;
 always_comb case(glyph)
'''
text+='\n'.join(f" 7'd{g}:begin lo=4'd{lo};hi=4'd{hi};end" for g,(lo,hi) in enumerate(bounds))
text+='''
 default:begin lo=0;hi=0;end endcase
 always @(posedge clk)begin
  row_d<=row;valid_d<=row>=lo&&row<hi;valid_q<=valid_d;
 end
 wire [9:0] body_addr=offset+row_d;
 assign data=valid_q?word[7:0]:8'd0;
`ifdef SYNTHESIS
 EFX_DPRAM10 #(.READ_WIDTH_A(10),.WRITE_WIDTH_A(10),.READ_WIDTH_B(10),.WRITE_WIDTH_B(10),
'''
text+=',\n'.join(f" .INIT_{i:X}(256'h{(number>>(256*i))&((1<<256)-1):064x})" for i in range(40))
text+='''
 ) storage(.CLKA(clk),.WEA(1'b0),.CLKEA(1'b1),.RSTA(1'b0),.ADDRENA(1'b1),.WDATAA(10'd0),.ADDRA({3'd0,glyph}),.RDATAA(offset),
 .CLKB(clk),.WEB(1'b0),.CLKEB(1'b1),.RSTB(1'b0),.ADDRENB(1'b1),.WDATAB(10'd0),.ADDRB(body_addr),.RDATAB(word));
`else
 // The native primitive is also tested with Efinity's simulation model.
 // Keep ordinary Icarus simulations independent of a vendor installation.
'''
text+=f" localparam [10239:0] CONTENTS=10240'h{number:02560x};\n"
text+=''' reg [9:0] mem[0:1023];reg [9:0] offset_q,word_q;integer i;
 initial for(i=0;i<1024;i=i+1)mem[i]=CONTENTS[i*10+:10];
 always @(posedge clk)begin offset_q<=mem[glyph];word_q<=mem[body_addr];end
 assign offset=offset_q;assign word=word_q;
`endif
endmodule
'''
if '--check' in sys.argv:
    assert target.read_text()==text,'Packed font is stale; run generate_osd_font.py'
else:
    target.write_text(text,encoding='utf-8')
print(f'PASS packed font: 96 offsets + {pointer-96} rows, {pointer}/1024 words')
