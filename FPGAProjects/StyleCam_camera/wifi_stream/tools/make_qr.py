"""Generate the audience QR codes from esp32s3_stream/config.h.

Outputs
  esp32s3_stream/qr_codes.h      two inline SVGs for the page (join the hotspot, open the page)
  docs/stylecam_qr_card.png      printable card for the demo table

The ESP32 has no internet, so the codes are rendered here once and committed; rerun after changing
AP_SSID / AP_PASSWORD.  Needs `qrcode` (pip install qrcode) and Pillow.
"""
from pathlib import Path
import re
import qrcode
from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
SKETCH = HERE.parent/'esp32s3_stream'
cfg = (SKETCH/'config.h').read_text(encoding='utf-8')
ssid = re.search(r'#define\s+AP_SSID\s+"([^"]*)"', cfg)[1]
password = re.search(r'#define\s+AP_PASSWORD\s+"([^"]*)"', cfg)[1]
url = 'http://192.168.4.1/'                       # softAP default address (no softAPConfig in the sketch)
esc = lambda s: re.sub(r'([\\;,:"])', r'\\\1', s)
wifi = f'WIFI:T:WPA;S:{esc(ssid)};P:{esc(password)};;' if password else f'WIFI:T:nopass;S:{esc(ssid)};;'


def matrix(text):
    q = qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_M, border=2)
    q.add_data(text); q.make(fit=True)
    return q.get_matrix()


def svg(m):
    n, d = len(m), []
    for y, row in enumerate(m):
        x = 0
        while x < n:
            if row[x]:
                s = x
                while x < n and row[x]: x += 1
                d.append(f'M{s} {y}h{x - s}v1h-{x - s}z')
            else:
                x += 1
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {n} {n}" shape-rendering="crispEdges">'
            f'<rect width="{n}" height="{n}" fill="#fff"/><path fill="#000" d="{"".join(d)}"/></svg>')


mw, mu = matrix(wifi), matrix(url)
(SKETCH/'qr_codes.h').write_text(
    '/* Generated by wifi_stream/tools/make_qr.py from config.h - do not edit. */\n#pragma once\n'
    f'/* {wifi.replace(password, "*" * len(password)) if password else wifi} */\n'
    f'static const char QR_WIFI_SVG[] PROGMEM = R"QR({svg(mw)})QR";\n'
    f'/* {url} */\nstatic const char QR_URL_SVG[] PROGMEM = R"QR({svg(mu)})QR";\n', encoding='ascii')

# Printable card: two codes side by side with short instructions.
font = lambda size: ImageFont.truetype('C:/Windows/Fonts/msyh.ttc', size)
card = Image.new('RGB', (1600, 1000), 'white'); d = ImageDraw.Draw(card)
d.text((800, 70), 'StyleCam 实时风格化 · 扫码互动', fill='black', font=font(64), anchor='mm')
for i, (m, title, sub) in enumerate([(mw, '① 扫码连接热点', f'WiFi：{ssid}   密码：{password or "无"}'),
                                     (mu, '② 扫码打开控制页', url)]):
    img = Image.new('1', (len(m), len(m)), 1)
    img.putdata([0 if v else 1 for row in m for v in row])
    img = img.resize((560, 560), Image.NEAREST).convert('RGB')
    x0 = 120 + i*800
    card.paste(img, (x0, 170))
    d.text((x0 + 280, 790), title, fill='black', font=font(48), anchor='mm')
    d.text((x0 + 280, 860), sub, fill='#444', font=font(32), anchor='mm')
d.text((800, 950), '同一时间最多 4 台手机观看；手机页面可切风格、混合风格、拍照和录像', fill='#666', font=font(28), anchor='mm')
out = HERE.parent/'docs'/'stylecam_qr_card.png'; out.parent.mkdir(exist_ok=True); card.save(out)
print('wrote', SKETCH/'qr_codes.h', 'and', out, f'({len(mw)}x{len(mw)} / {len(mu)}x{len(mu)} modules)')
